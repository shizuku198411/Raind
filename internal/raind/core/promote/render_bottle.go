package promote

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"
)

func RenderBottlefile(d BottleDraft) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by Raind Promote from %s.\n", d.SourceContainer)
	fmt.Fprintln(&b, "# This bottle.yaml is a reviewable draft, not production configuration.")
	fmt.Fprintln(&b, "# Review env, mounts, ports, dependencies, and secret candidates before sharing.")
	if len(d.Warnings) > 0 {
		fmt.Fprintln(&b, "#")
		fmt.Fprintln(&b, "# Warnings:")
		for _, w := range d.Warnings {
			fmt.Fprintf(&b, "# - %s: %s\n", w.Code, w.Message)
		}
	}
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "bottle:")
	fmt.Fprintf(&b, "  name: %s\n", quoteYAMLString(d.BottleName))
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "services:")
	for _, svc := range bottleDraftServices(d) {
		renderService(&b, svc)
	}
	if len(d.Policies) > 0 {
		fmt.Fprintln(&b)
		fmt.Fprintln(&b, "policies:")
		for _, policy := range d.Policies {
			renderPolicy(&b, policy)
		}
	}
	return b.Bytes(), nil
}

